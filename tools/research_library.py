#!/usr/bin/env python3.12
"""The research library (Barry 2026-11-13): every angle report tools/abpage.py paid for, indexed by the page it was
done for, so the five angles a page did not use can be reused later (a second section, a new page on the same
products, a comparison, a fact check).

Each research-method page runs six angle agents (A Normalise, B Derive, C Compatibility, D Mechanism, E Named
measurements, F Whole category, priced) and the composer uses one. All six reports are kept, committed, in
growth/focus/ab/<folder>/angle-<X>.json; the folder is the page's slug, except for new pages, whose folder is the
research batch name and whose page slug is in draft.json. This script writes:

    growth/focus/ab/library.json   one row per page: page slug and URL, the query, the angle used, and for every angle
                                   its gap sentence, standout score (0-3), what it decides, products covered, finding
                                   count, sources, model and date, plus the file path
    growth/focus/ab/LIBRARY.md     the same as a readable table, unused angles marked

Only the used angle went through the source verifier (verify.json); the other five are the researcher's own findings,
each with a source URL and read date, and should be re-checked before they are published.

    python3.12 tools/research_library.py build
    python3.12 tools/research_library.py find "AC180" [--angle B] [--unused]   # findings that mention it, with sources
    python3.12 tools/research_library.py page <slug>                            # one page's six reports, summarised

tools/abpage.py runs `build` after each research batch.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AB = ROOT / "growth/focus/ab"
NAMES = {"A": "Normalise", "B": "Derive", "C": "Compatibility", "D": "Mechanism", "E": "Named measurements",
         "F": "Whole category, priced"}


def _j(p: Path) -> dict:
    try:
        return json.loads(p.read_text())
    except (OSError, ValueError):
        return {}


def _live() -> set[str]:
    sys.path.insert(0, str(ROOT / "src"))
    import gaps
    return {g["slug"] for g in gaps.GAP_PAGES}


def rows() -> list[dict]:
    live = _live()
    out = []
    for d in sorted(AB.iterdir()):
        files = sorted(d.glob("angle-*.json")) if d.is_dir() else []
        if not files:
            continue
        draft, comp, harv = _j(d / "draft.json"), _j(d / "compose.json"), _j(d / "harvest.json")
        slug = draft.get("slug") or d.name
        used = draft.get("angle") or comp.get("angle")
        angles = []
        for f in files:
            a = _j(f)
            x = f.stem.split("-")[1]
            fnd = a.get("findings") or []
            prods = list(dict.fromkeys([str(v.get("product")) for v in fnd if v.get("product")] + [str(c) for c in a.get("candidates") or []]))
            dates = sorted({str(v.get("read")) for v in fnd if v.get("read")})
            angles.append({
                "angle": x, "name": NAMES.get(x, x), "used": x == used, "status": a.get("status") or ("ok" if fnd else "empty"),
                "gap": a.get("gap"), "standout": a.get("standout"), "decides": a.get("decides"),
                "findings": len(fnd), "sources": len({v.get("source") for v in fnd if v.get("source")}),
                "products": prods[:40], "read": dates[-1] if dates else None,
                "model": (a.get("_meta") or {}).get("model"), "file": str(f.relative_to(ROOT))})
        out.append({"folder": d.name, "slug": slug, "url": f"https://dealectric.com/{slug}" if slug in live else None,
                    "query": draft.get("query") or next((c.get("typed") for c in harv.get("chats", []) if c.get("typed")), None),
                    "used": used, "why_used": draft.get("why_angle") or comp.get("why_angle"),
                    "verified": (d / "verify.json").exists(), "angles": angles})
    return out


def build() -> None:
    rs = rows()
    (AB / "library.json").write_text(json.dumps({"pages": rs}, indent=1, ensure_ascii=False) + "\n")
    n_ang = sum(len(r["angles"]) for r in rs)
    n_unused = sum(1 for r in rs for a in r["angles"] if not a["used"] and a["findings"])
    lines = ["# Research library", "",
             f"Generated by `tools/research_library.py build`. {len(rs)} pages, {n_ang} angle reports, {n_unused} unused "
             "reports with findings. Only the used angle (**bold**) went through the source verifier; re-check an unused "
             "report's findings at their sources before publishing them. Search: `python3.12 tools/research_library.py find <words>`.", "",
             "| Page | Query | Used | Unused angles (standout 0-3, findings) |", "|---|---|---|---|"]
    for r in rs:
        page = f"[{r['slug']}]({r['url']})" if r["url"] else r["slug"]
        un = "; ".join(f"{a['angle']} {a['name']} ({a['standout']}, {a['findings']})" for a in r["angles"] if not a["used"])
        q = (r["query"] or "").replace("|", "/")[:90]
        lines.append(f"| {page} | {q} | **{r['used'] or '-'}** | {un} |")
    (AB / "LIBRARY.md").write_text("\n".join(lines) + "\n")
    print(f"library: {len(rs)} pages, {n_ang} angle reports ({n_unused} unused with findings) -> growth/focus/ab/library.json, LIBRARY.md")


def find(words: str, angle: str | None, unused: bool) -> None:
    pat = re.compile(re.escape(words), re.I)
    for r in rows():
        for a in r["angles"]:
            if (angle and a["angle"] != angle) or (unused and a["used"]):
                continue
            rep = _j(ROOT / a["file"])
            for v in rep.get("findings") or []:
                if pat.search(json.dumps(v, ensure_ascii=False)):
                    print(f"{r['slug']} [{a['angle']} {a['name']}{', used' if a['used'] else ''}] {v.get('product')}: "
                          f"{v.get('label')} = {v.get('value')}  ({v.get('source')}, read {v.get('read')})")


def page(slug: str) -> None:
    for r in rows():
        if slug in (r["slug"], r["folder"]):
            print(f"{r['slug']}  query: {r['query']}\nused: {r['used']}  {r['why_used'] or ''}\n")
            for a in r["angles"]:
                print(f"{a['angle']} {a['name']}{'  [USED]' if a['used'] else ''}  standout {a['standout']}, "
                      f"{a['findings']} findings, {a['sources']} sources, read {a['read']}\n   gap: {a['gap']}\n   file: {a['file']}\n")
            return
    print("no research for", slug)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["build", "find", "page"])
    ap.add_argument("arg", nargs="?")
    ap.add_argument("--angle")
    ap.add_argument("--unused", action="store_true")
    a = ap.parse_args()
    if a.cmd == "build":
        build()
    elif a.cmd == "find":
        find(a.arg, a.angle, a.unused)
    else:
        page(a.arg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
